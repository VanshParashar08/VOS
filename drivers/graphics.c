static uint32_t fb_address = 0;
static uint32_t fb_w = 0;
static uint32_t fb_h = 0;
static uint32_t fb_p = 0;
static uint8_t fb_bytes_per_pixel = 4;

void graphics_init(uint32_t fb_addr, uint32_t width, uint32_t height, uint32_t pitch, uint8_t bpp) {
    fb_address = fb_addr;
    fb_w = width;
    fb_h = height;
    fb_p = pitch;
    fb_bytes_per_pixel = bpp / 8;
}

uint32_t get_screen_width(void) { return fb_w; }
uint32_t get_screen_height(void) { return fb_h; }

void put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= fb_w || y >= fb_h) return;
    
    uint32_t offset = (y * fb_p) + (x * fb_bytes_per_pixel);
    
    if (fb_bytes_per_pixel == 4) {
        *((volatile uint32_t*)(fb_address + offset)) = color;
    } else if (fb_bytes_per_pixel == 3) {
        volatile uint8_t* p = (volatile uint8_t*)(fb_address + offset);
        p[0] = color & 0xFF;
        p[1] = (color >> 8) & 0xFF;
        p[2] = (color >> 16) & 0xFF;
    }
}

void draw_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    for (uint32_t i = 0; i < h; i++) {
        for (uint32_t j = 0; j < w; j++) {
            put_pixel(x + j, y + i, color);
        }
    }
}

void draw_char(uint32_t x, uint32_t y, char c, uint32_t fg_color, uint32_t bg_color) {
    if (c < 0 || c > 127) return; // Only basic ASCII supported
    
    const uint8_t* glyph = font8x8[(int)c];
    
    for (uint32_t row = 0; row < 8; row++) {
        for (uint32_t col = 0; col < 8; col++) {
            if (glyph[row] & (1 << (7 - col))) {
                put_pixel(x + col, y + row, fg_color);
            } else if (bg_color != 0xFFFFFFFF) { 
                // 0xFFFFFFFF can be used as a special "transparent" background flag
                put_pixel(x + col, y + row, bg_color);
            }
        }
    }
}

void draw_string(uint32_t x, uint32_t y, const char* str, uint32_t fg_color, uint32_t bg_color) {
    uint32_t start_x = x;
    while (*str) {
        if (*str == '\n') {
            y += 10;
            x = start_x;
        } else {
            draw_char(x, y, *str, fg_color, bg_color);
            x += 8;
        }
        str++;
    }
}

void draw_char_scaled(uint32_t x, uint32_t y, char c, uint32_t fg_color, uint32_t bg_color, uint32_t scale) {
    if (c < 0 || c > 127) return;
    
    const uint8_t* glyph = font8x8[(int)c];
    
    for (uint32_t row = 0; row < 8; row++) {
        for (uint32_t col = 0; col < 8; col++) {
            if (glyph[row] & (1 << (7 - col))) {
                draw_rect(x + col * scale, y + row * scale, scale, scale, fg_color);
            } else if (bg_color != 0xFFFFFFFF) { 
                draw_rect(x + col * scale, y + row * scale, scale, scale, bg_color);
            }
        }
    }
}

void draw_string_scaled(uint32_t x, uint32_t y, const char* str, uint32_t fg_color, uint32_t bg_color, uint32_t scale) {
    uint32_t start_x = x;
    while (*str) {
        if (*str == '\n') {
            y += 10 * scale;
            x = start_x;
        } else {
            draw_char_scaled(x, y, *str, fg_color, bg_color, scale);
            x += 8 * scale;
        }
        str++;
    }
}

void draw_image_scaled(uint32_t x, uint32_t y, uint32_t w, uint32_t h, const uint32_t* data, uint32_t scale) {
    for (uint32_t row = 0; row < h; row++) {
        for (uint32_t col = 0; col < w; col++) {
            uint32_t color = data[row * w + col];
            draw_rect(x + col * scale, y + row * scale, scale, scale, color);
        }
    }
}
