# IRQ Stubs (Hardware interrupts mapped to 32+)
.macro IRQ num, irq_num
  .global irq\irq_num
  irq\irq_num:
    cli
    push $0
    push $\num
    jmp irq_common_stub
.endm

IRQ 32, 0 # Timer
IRQ 33, 1 # Keyboard
IRQ 44, 12 # Mouse

.extern isr_handler
isr_common_stub:
    pusha
    mov %ds, %ax
    push %eax
    mov $0x10, %ax
    mov %ax, %ds
    mov %ax, %es
    mov %ax, %fs
    mov %ax, %gs
    push %esp
    call isr_handler
    add $4, %esp
    pop %eax
    mov %ax, %ds
    mov %ax, %es
    mov %ax, %fs
    mov %ax, %gs
    popa
    add $8, %esp
    sti
    iret

